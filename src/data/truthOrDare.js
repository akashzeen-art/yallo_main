export const TOD_LEVELS = ["fun", "flirty", "bold"];
const LEVEL_DECKS = { fun: FUN, flirty: FLIRTY, bold: BOLD };

const decks = new Map();
function drawFrom(key, list) {
  let deck = decks.get(key);
  if (!deck || !deck.length) {
    deck = list.slice().sort(() => Math.random() - 0.5);
    decks.set(key, deck);
  }
  return deck.pop();
}

/** Non-repeating prompt for the user, or (forCharacter) one the character can do in chat */
export function drawTodPrompt(kind, level = "flirty", lang = "en", forCharacter = false) {
  const code = lang === "es" || lang === "fr" ? lang : "en";
  const pack = (LEVEL_DECKS[level] || FLIRTY)[code];
  const list = forCharacter && kind === "dare" && level !== "bold" ? CHAT_DARES[code] : pack[kind];
  return drawFrom(`${forCharacter ? "c" : "u"}:${kind}:${level}:${code}`, list);
}

